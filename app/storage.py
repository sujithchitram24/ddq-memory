"""File storage behind a tiny interface.

Local disk for development; in production the same interface is implemented with S3
(put_object/get_object). Keys are generated by us (org_id/sha256.ext), never derived
from the user's filename, so path traversal ("../../etc/passwd") is impossible.
"""
import re
from pathlib import Path
from typing import Protocol

KEY_PATTERN = re.compile(r"^[0-9a-f-]{36}/[0-9a-f]{64}\.(pdf|docx|xlsx)$")


class Storage(Protocol):
    def put(self, key: str, data: bytes) -> None: ...
    def get(self, key: str) -> bytes: ...


class LocalStorage:
    def __init__(self, root: str) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        if not KEY_PATTERN.match(key):
            raise ValueError("invalid storage key")
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise ValueError("storage key escapes root")
        return path

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_bytes(data)
        tmp.replace(path)  # atomic rename: readers never see a half-written file

    def get(self, key: str) -> bytes:
        return self._path(key).read_bytes()
