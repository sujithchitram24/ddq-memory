"""Reproducible experiment: fresh org -> upload corpus -> process -> evaluate -> write report.

Usage:
  uv run python -m scripts.run_eval                       # deterministic, offline
  uv run python -m scripts.run_eval --provider anthropic  # needs ANTHROPIC_API_KEY (costs money)

Writes reports/results.md and reports/results.json. Every number in the report comes
from this script; do not hand-edit them.
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

from sqlalchemy import select

from app.answering.providers import get_provider
from app.config import get_settings
from app.db import make_engine, make_session_factory
from app.documents import register_document
from app.evaluation.dataset import load_dataset
from app.evaluation.runner import run_evaluation
from app.models import EvalResult
from app.storage import LocalStorage
from app.worker import drain
from scripts.create_org import create_org

ROOT = Path(__file__).resolve().parent.parent
METRICS = [
    ("correct", "answerable_total", "Correct answer"),
    ("association", "answerable_total", "Value + labels together in cited evidence"),
    ("citation_ok", "answerable_total", "Cited evidence contains the values"),
    ("retrieval_hit", "answerable_total", "Retrieved evidence contains values + labels"),
    ("false_abstentions", "answerable_total", "Abstained although answerable"),
    ("correct_abstentions", "should_abstain_total", "Correct abstention (answer missing)"),
    ("answered_when_should_abstain", "should_abstain_total", "Answered although answer missing"),
]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--provider", default="deterministic", choices=["deterministic", "anthropic"])
    args = ap.parse_args()

    settings = get_settings()
    factory = make_session_factory(make_engine(settings.database_url))
    storage = LocalStorage(settings.storage_dir)
    ds = load_dataset()

    with factory() as s:
        org_id, _ = create_org(s, "evaluation (fresh)")
        for name in ds.funds.values():
            register_document(s, storage, settings, org_id=org_id, filename=name, data=(ROOT / "corpus" / name).read_bytes())
    outcomes = drain(factory, storage, worker_id="eval-script")
    print(f"processing outcomes: {outcomes}")

    provider = get_provider(args.provider, settings.anthropic_api_key, settings.llm_model)
    with factory() as s:
        run = run_evaluation(s, org_id, ds, provider, ["flat", "structured"], [50, 200])
        results = s.scalars(select(EvalResult).where(EvalResult.eval_run_id == run.id)).all()
        write_report(run, results, ds)
    print(f"eval_run_id={run.id}")
    print((ROOT / "reports" / "results.md").read_text())


def _answer_text(r) -> str:
    a = r.answer.get("answer")
    return a.get("answer", "") if isinstance(a, dict) else str(r.answer.get("error", r.answer))


def write_report(run, results, ds) -> None:
    out = ROOT / "reports"
    out.mkdir(exist_ok=True)
    configs = list(run.summary)
    lines = [
        "# Results (generated by scripts/run_eval.py - do not edit by hand)",
        "",
        f"- eval_run_id: `{run.id}`",
        f"- provider: `{run.config['provider']}`, top_k: {run.config['top_k']}",
        f"- dataset sha256: `{run.dataset_sha256[:16]}...` ({len(ds.questions)} questions)",
        "",
        "## Summary (counts / denominator)",
        "",
        "| Metric | " + " | ".join(configs) + " |",
        "|---|" + "---|" * len(configs),
    ]
    for key, denom, label in METRICS:
        cells = [f"{run.summary[c][key]}/{run.summary[c][denom]}" for c in configs]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    lines.append("| Unsupported number claims | " + " | ".join(str(run.summary[c]["unsupported_number_claims"]) for c in configs) + " |")
    lines.append("| Errors | " + " | ".join(str(run.summary[c]["errors"]) for c in configs) + " |")

    by_q: dict[str, dict[str, EvalResult]] = defaultdict(dict)
    for r in results:
        by_q[r.question_id][f"{r.strategy}/{r.chunk_size}"] = r
    qmap = {q.id: q for q in ds.questions}

    lines += ["", "## Per question (correct / association)", "", "Legend: `C`=correct, `A`=association, `-`=no, `ab`=abstained", "",
              "| Question | Category | " + " | ".join(configs) + " |", "|---|---|" + "---|" * len(configs)]
    for qid in sorted(by_q, key=lambda x: [q.id for q in ds.questions].index(x)):
        cells = []
        for c in configs:
            s = by_q[qid][c].scores
            if qmap[qid].should_abstain:
                cells.append("ab ✓" if s.get("abstained") else "answered ✗")
            else:
                cells.append(("C" if s.get("correct") else "-") + ("A" if s.get("association") else "-") + (" ab" if s.get("abstained") else ""))
        lines.append(f"| {qid} | {qmap[qid].category} | " + " | ".join(cells) + " |")

    lines += ["", "## Answers for questions where strategies disagree (chunk size 50)", ""]
    for qid, cfgs in by_q.items():
        f, st = cfgs.get("flat/50"), cfgs.get("structured/50")
        if f and st and (f.scores.get("correct"), f.scores.get("association")) != (st.scores.get("correct"), st.scores.get("association")):
            lines.append(f"**{qid}** - {qmap[qid].question}")
            lines.append(f"- expected: {qmap[qid].expected_values or 'abstain'}")
            lines.append(f"- flat/50: `{_answer_text(f)}`")
            lines.append(f"- structured/50: `{_answer_text(st)}`")
            lines.append("")
    (out / "results.md").write_text("\n".join(lines) + "\n")
    (out / "results.json").write_text(json.dumps({"eval_run_id": str(run.id), "config": run.config, "summary": run.summary},
                                                 indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
